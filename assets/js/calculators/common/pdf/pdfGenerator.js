/* =========================================================
   ToolZen Hub
   Global PDF Generator
========================================================= */

import {
    createPDFDocument
} from "./pdfDocument.js";

import {
    loadPdfLibraries
} from "./pdfLoader.js";

import {
    addPDFTitle,
    addPDFSummary,
    addPDFTable,
    addPDFFooter
} from "./pdfTable.js";

import {
    downloadPDF
} from "./pdfDownload.js";


/* =========================================================
   GENERATE PDF
========================================================= */

export async function generatePDF({

    filename = "toolzen-report.pdf",

    title = "ToolZen Hub Report",

    subtitle = "",

    summary = [],

    columns = [],

    rows = [],

    footer = "Generated by ToolZen Hub"

} = {}) {

    try {

        /*
         * Create PDF
         *
         * This automatically loads
         * jsPDF + AutoTable.
         */
        const doc =
            await loadPdfLibraries();
            await createPDFDocument();
         


        /*
         * Title
         */
        addPDFTitle(
            doc,
            title,
            subtitle
        );


        /*
         * Summary
         */
        if (
            Array.isArray(summary) &&
            summary.length > 0
        ) {

            addPDFSummary(
                doc,
                summary
            );

        }


        /*
         * Table
         */
        if (
            Array.isArray(columns) &&
            columns.length > 0 &&
            Array.isArray(rows) &&
            rows.length > 0
        ) {

            addPDFTable(
                doc,
                columns,
                rows
            );

        }


        /*
         * Footer
         */
        addPDFFooter(
            doc,
            footer
        );


        /*
         * Download
         */
        downloadPDF(
            doc,
            filename
        );


        return true;

    } catch (error) {

        console.error(
            "PDF generation failed:",
            error
        );


        return false;

    }

}
