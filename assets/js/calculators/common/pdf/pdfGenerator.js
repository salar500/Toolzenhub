/* =========================================================
   ToolZen Hub
   Global PDF Generator
========================================================= */

import {
    loadPdfLibraries
} from "./pdfLoader.js";

import {
    createPDFDocument
} from "./pdfDocument.js";

import {
    addPDFTitle,
    addPDFSummary,
    addPDFTable,
    addPDFFooter,
    ensurePDFWatermark
} from "./pdfTable.js";


import {
    downloadPDF
} from "./pdfDownload.js";


/* =========================================================
   GENERATE PDF
========================================================= */

export async function generatePDF({

    filename =
        "toolzen-report.pdf",

    title =
        "ToolZen Hub Report",

    subtitle =
        "",

    summary =
        [],

    columns =
        [],

    rows =
        [],

    footer =
        "Generated by ToolZen Hub",

    watermark =
        "TOOLZEN HUB",

    metadata =
        {}

} = {}) {

    try {

        /* =================================================
           LOAD PDF LIBRARIES
        ================================================= */

        await loadPdfLibraries();


        /* =================================================
           CREATE PDF DOCUMENT
        ================================================= */

        const doc =
            await createPDFDocument();


        /* =================================================
           DOCUMENT METADATA
        ================================================= */

        if (
            typeof doc.setProperties ===
            "function"
        ) {

            doc.setProperties({

                title:
                    String(title),

                subject:
                    String(
                        subtitle ||
                        "ToolZen Hub Report"
                    ),

                author:
                    "ToolZen Hub",

                creator:
                    "ToolZen Hub",

                keywords:
                    Object.keys(metadata)
                        .map(
                            key =>
                                `${key}:${metadata[key]}`
                        )
                        .join(", ")

            });

        }


        /* =================================================
           TITLE
        ================================================= */

        addPDFTitle(
            doc,
            title,
            subtitle
        );


        /* =================================================
           SUMMARY
        ================================================= */

        if (
            Array.isArray(summary) &&
            summary.length > 0
        ) {

            addPDFSummary(
                doc,
                summary
            );

        }


        /* =================================================
           TABLE
        ================================================= */

        if (
            Array.isArray(columns) &&
            columns.length > 0 &&
            Array.isArray(rows) &&
            rows.length > 0
        ) {

            addPDFTable(
                doc,
                columns,
                rows
            );

        }


        /* =================================================
           WATERMARK
        ================================================= */

        /*
         * The standard watermark text is defined in
         * pdfStyles.js.
         *
         * The "watermark" option is retained here so
         * existing/future calculators can customize it.
         *
         * Currently the global ToolZen watermark is used
         * by the PDF table layer.
         */
        void watermark;


        ensurePDFWatermark(
            doc
        );


        /* =================================================
           FOOTER
        ================================================= */

        addPDFFooter(
            doc,
            footer
        );


        /* =================================================
           DOWNLOAD
        ================================================= */

        downloadPDF(
            doc,
            filename
        );


        return true;

    } catch (error) {

        console.error(
            "PDF generation failed:",
            error
        );


        return false;

    }

}
