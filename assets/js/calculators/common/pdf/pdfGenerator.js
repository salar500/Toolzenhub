/* =========================================================
   ToolZen Hub
   Global PDF Generator
========================================================= */

import {
    loadPdfLibraries
} from "./pdfLoader.js";

import {
    createPDFDocument
} from "./pdfDocument.js";

import {
    addPDFTitle,
    addPDFSummary,
    addPDFTable,
    addPDFFooter
} from "./pdfTable.js";

import {
    downloadPDF
} from "./pdfDownload.js";


/* =========================================================
   GENERATE PDF
========================================================= */

export async function generatePDF({

    filename = "toolzen-report.pdf",

    title = "ToolZen Hub Report",

    subtitle = "",

    summary = [],

    columns = [],

    rows = [],

    footer = "Generated by ToolZen Hub"

} = {}) {

    try {

        /* =================================================
           LOAD PDF LIBRARIES
        ================================================= */

        await loadPdfLibraries();


        /* =================================================
           CREATE PDF DOCUMENT
        ================================================= */

        const doc =
            await createPDFDocument();


        /* =================================================
           TITLE
        ================================================= */

        addPDFTitle(
            doc,
            title,
            subtitle
        );


        /* =================================================
           SUMMARY
        ================================================= */

        if (
            Array.isArray(summary) &&
            summary.length > 0
        ) {

            addPDFSummary(
                doc,
                summary
            );

        }


        /* =================================================
           TABLE
        ================================================= */

        if (
            Array.isArray(columns) &&
            columns.length > 0 &&
            Array.isArray(rows) &&
            rows.length > 0
        ) {

            addPDFTable(
                doc,
                columns,
                rows
            );

        }


        /* =================================================
           FOOTER
        ================================================= */

        addPDFFooter(
            doc,
            footer
        );


        /* =================================================
           DOWNLOAD
        ================================================= */

        downloadPDF(
            doc,
            filename
        );


        return true;

    } catch (error) {

        console.error(
            "PDF generation failed:",
            error
        );


        return false;

    }

}
