/* =========================================================
   ToolZen Hub
   Central Routes

   Supports:
   - GitHub Pages
   - Hostinger / Production Domain
========================================================= */


/* =========================================================
   SITE ROOT
========================================================= */

const SITE_ROOT =
    window.location.hostname ===
    "salar500.github.io"
        ? "/Toolzenhub/"
        : "/";



/* =========================================================
   ROUTES
========================================================= */

export const ROUTES = {


    /* =====================================================
       HOME
    ===================================================== */

    home:
        SITE_ROOT,


    /* =====================================================
       CATEGORIES
    ===================================================== */

    categories:
        `${SITE_ROOT}categories.html`,


    /* =====================================================
       LOANS
    ===================================================== */

    loans:
        `${SITE_ROOT}loans.html`,


    /* =====================================================
       ARTICLES
    ===================================================== */

    articles:
        `${SITE_ROOT}articles.html`,


    /* =====================================================
       INDIVIDUAL ARTICLE
    ===================================================== */

    article(
        topic,
        slug
    ) {

        return (
            `${SITE_ROOT}articles/` +
            `${topic}/${slug}/`
        );

    },


    /* =====================================================
       ABOUT
    ===================================================== */

    about:
        `${SITE_ROOT}about.html`,


    /* =====================================================
       CONTACT
    ===================================================== */

    contact:
        `${SITE_ROOT}contact.html`,


    /* =====================================================
       TERMS
    ===================================================== */

    terms:
        `${SITE_ROOT}terms.html`,


    /* =====================================================
       DISCLAIMER
    ===================================================== */

    disclaimer:
        `${SITE_ROOT}disclaimer.html`,


    /* =====================================================
       PRIVACY POLICY
    ===================================================== */

    privacy:
        `${SITE_ROOT}privacy.html`,


    /* =====================================================
       ALL CALCULATORS
    ===================================================== */

    calculators:
        `${SITE_ROOT}calculators.html`,


    /* =====================================================
       INDIVIDUAL CALCULATOR
    ===================================================== */

    calculator(
        slug
    ) {

        return (
            `${SITE_ROOT}calculators/` +
            `${slug}/`
        );

    }

};
